func byteArrayToHexString(_ byteArray: [UInt8], minDigit: Int = 2) -> String {
  return byteArray.map {
    var hexString = String($0, radix: 16)
    if hexString.count < minDigit {
      hexString = String(repeating: "0", count: minDigit - hexString.count) + hexString
    }
    return hexString
  }.joined()
}

