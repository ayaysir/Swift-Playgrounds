func hexStringToByteArray1(_ hexString: String) -> [UInt8] {
  let stringArray = hexString.map(String.init)
  var byteArray = [UInt8]()
  for i in stride(from: 0, to: stringArray.count, by: 2) {
    byteArray.append(UInt8(stringArray[i] + stringArray[i + 1], radix: 16) ?? 0)
  }
  return byteArray
